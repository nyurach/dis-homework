    (1, 'Everyday Mathematics', 5, 1),
    (2, 'Introduction to Physics', 10, 2),
    (3, 'Algebra Foundations', 8, 1)
) AS sample (id, title, grade_level, teacher_id)
WHERE NOT EXISTS (SELECT 1 FROM courses);

