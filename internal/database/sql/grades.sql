CREATE TABLE IF NOT EXISTS grades (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL CHECK (student_id > 0),
    course_id bigint NOT NULL CHECK (course_id > 0),
    teacher_id bigint NOT NULL CHECK (teacher_id > 0),
    grade numeric(5, 2) NOT NULL CHECK (grade BETWEEN 0 AND 100),
    UNIQUE (student_id, course_id)
);

-- Add sample records only when the table is empty.
INSERT INTO grades (id, student_id, course_id, teacher_id, grade)
SELECT * FROM (VALUES
    (1, 1, 1, 1, 88),
    (2, 2, 2, 2, 92),
    (3, 3, 3, 1, 85)
) AS sample (id, student_id, course_id, teacher_id, grade)
WHERE NOT EXISTS (SELECT 1 FROM grades);

-- Keep generated IDs above the sample IDs without rewinding the sequence.
SELECT setval(
    pg_get_serial_sequence('grades', 'id'),
    GREATEST(
        (SELECT MAX(id) FROM grades),
        pg_sequence_last_value(pg_get_serial_sequence('grades', 'id')::regclass)
    )
);
