CREATE TABLE IF NOT EXISTS videos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (length(trim(name)) > 0),
    address text NOT NULL CHECK (address ~ '^https?://'),
    course_id bigint NOT NULL CHECK (course_id > 0)
);

-- Add sample records only when the table is empty.
INSERT INTO videos (id, name, address, course_id)
SELECT * FROM (VALUES
    (1, 'Understanding fractions', 'https://example.org/fractions.mp4', 1),
    (2, 'Forces and motion', 'https://example.org/forces.mp4', 2),
    (3, 'Solving equations', 'https://example.org/equations.mp4', 3)
) AS sample (id, name, address, course_id)
WHERE NOT EXISTS (SELECT 1 FROM videos);

-- Keep generated IDs above the sample IDs without rewinding the sequence.
SELECT setval(
    pg_get_serial_sequence('videos', 'id'),
    GREATEST(
        (SELECT MAX(id) FROM videos),
        pg_sequence_last_value(pg_get_serial_sequence('videos', 'id')::regclass)
    )
);
