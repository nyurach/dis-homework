CREATE TABLE IF NOT EXISTS teachers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username text NOT NULL UNIQUE,
    full_name text NOT NULL CHECK (length(trim(full_name)) > 0),
    subject text NOT NULL
);

-- Add sample records only when the table is empty.
INSERT INTO teachers (id, username, full_name, subject)
SELECT * FROM (VALUES
    (1, 'sara', 'Sara Ahmed', 'Mathematics'),
    (2, 'daniel', 'Daniel Lee', 'Science')
) AS sample (id, username, full_name, subject)
WHERE NOT EXISTS (SELECT 1 FROM teachers);

-- Keep generated IDs above the sample IDs without rewinding the sequence.
SELECT setval(
    pg_get_serial_sequence('teachers', 'id'),
    GREATEST(
        (SELECT MAX(id) FROM teachers),
        pg_sequence_last_value(pg_get_serial_sequence('teachers', 'id')::regclass)
    )
);
